  function slot(d){ const m = d.getHours()*60 + d.getMinutes();
    return m < 300 ? 'dawn' : m < 540 ? 'morning' : m < 690 ? 'am' : m < 810 ? 'lunch' : m < 960 ? 'pm' : m < 1080 ? 'late' : m < 1260 ? 'evening' : 'night'; }

  function get(ctx){
    const d = new Date(), sl = slot(d), wd = d.getDay();
    if (wd === 1 && sl === 'morning') return SPECIAL.mon;
    if (wd === 5 && (sl === 'pm' || sl === 'late')) return SPECIAL.fri;
    if ((wd === 0 || wd === 6) && (sl === 'morning' || sl === 'am')) return SPECIAL.weekend;
    const list = POOL[sl].filter(x => !x.only || x.only === ctx);
    const day = Math.floor((d - new Date(d.getFullYear(), 0, 1)) / 864e5);
    return list[day % list.length];
  }
  window.EPGreet = {get};
